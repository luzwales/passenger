using System.Text;

namespace Passenger.Linq;

/// <summary>Generates a self-contained strongly-typed <c>TypedDataContext.g.cs</c> from a <see cref="LinqDatabaseSchema"/>:
/// - For SQLite &amp; PostgreSQL: EF Core <c>DbContext</c> with <c>DbSet&lt;TRow&gt;</c> properties per table,
///   auto-logging generated SQL to <c>Passenger.Linq.Runtime.LinqDumper.LogSql</c>.
/// - For CSV &amp; XLSX: zero-dependency in-memory strongly-typed collections (<c>IReadOnlyList&lt;TRow&gt;</c>)
///   parsed directly from the file on disk.</summary>
public static class LinqContextGenerator
{
    public const string DefaultContextTypeName = "TypedDataContext";

    public static string Generate(LinqDatabaseSchema schema, string? targetPathLiteral = null)
    {
        ArgumentNullException.ThrowIfNull(schema);
        return schema.Kind switch
        {
            LinqDataSourceKind.Sqlite or LinqDataSourceKind.PostgreSql or LinqDataSourceKind.SqlServer => GenerateEfContext(schema),
            LinqDataSourceKind.MySql => GenerateMySqlContext(schema),
            LinqDataSourceKind.Csv => GenerateCsvContext(schema, targetPathLiteral),
            LinqDataSourceKind.Xlsx => GenerateXlsxContext(schema, targetPathLiteral),
            LinqDataSourceKind.Json => GenerateJsonContext(schema, targetPathLiteral),
            _ => throw new ArgumentOutOfRangeException(nameof(schema)),
        };
    }

    private static string GenerateEfContext(LinqDatabaseSchema schema)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.ComponentModel.DataAnnotations;");
        sb.AppendLine("using System.ComponentModel.DataAnnotations.Schema;");
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        sb.AppendLine("using Passenger.Linq.Runtime;");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            List<LinqColumnSchema> pkCols = [.. table.Columns.Where(c => c.IsPrimaryKey)];
            if (string.IsNullOrEmpty(table.SchemaName))
            {
                sb.AppendLine($"[Table({Quote(table.TableName)})]");
            }
            else
            {
                sb.AppendLine($"[Table({Quote(table.TableName)}, Schema = {Quote(table.SchemaName)})]");
            }
            if (pkCols.Count > 1)
            {
                string pkArgs = string.Join(", ", pkCols.Select(c => $"nameof({c.PropertyName})"));
                sb.AppendLine($"[PrimaryKey({pkArgs})]");
            }
            sb.AppendLine($"public sealed class {table.EntityTypeName}");
            sb.AppendLine("{");
            foreach (LinqColumnSchema col in table.Columns)
            {
                if (col.IsPrimaryKey && pkCols.Count == 1)
                {
                    sb.AppendLine("    [Key]");
                }
                sb.AppendLine($"    [Column({Quote(col.Name)})]");
                string typeDecl = col.IsNullable && !col.ClrTypeName.EndsWith('?') ? col.ClrTypeName + "?" : col.ClrTypeName;
                string defaultInit = !col.IsNullable && col.ClrTypeName is "string" or "byte[]" ? " = default!;" : string.Empty;
                sb.AppendLine($"    public {typeDecl} {col.PropertyName} {{ get; set; }}{defaultInit}");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine($"public sealed class {DefaultContextTypeName} : DbContext");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly string _connectionString;");
        sb.AppendLine();
        sb.AppendLine($"    public {DefaultContextTypeName}(string? connectionString = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        _connectionString = !string.IsNullOrEmpty(connectionString)");
        sb.AppendLine("            ? connectionString");
        sb.AppendLine("            : Environment.GetEnvironmentVariable(\"PASSENGER_LINQ_CONNECTION\") ?? string.Empty;");
        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            sb.AppendLine($"    public DbSet<{table.EntityTypeName}> {table.PropertyName} => Set<{table.EntityTypeName}>();");
        }
        sb.AppendLine();

        sb.AppendLine("    protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)");
        sb.AppendLine("    {");
        if (schema.Kind == LinqDataSourceKind.Sqlite)
        {
            sb.AppendLine("        optionsBuilder.UseSqlite(_connectionString);");
        }
        else if (schema.Kind == LinqDataSourceKind.PostgreSql)
        {
            sb.AppendLine("        optionsBuilder.UseNpgsql(_connectionString);");
        }
        else if (schema.Kind == LinqDataSourceKind.SqlServer)
        {
            sb.AppendLine("        optionsBuilder.UseSqlServer(_connectionString);");
        }
        sb.AppendLine("        optionsBuilder.LogTo(sql => LinqExtensions.LogSql(sql), new[] { Microsoft.EntityFrameworkCore.Diagnostics.RelationalEventId.CommandExecuted });");
        sb.AppendLine("    }");

        if (schema.Tables.Any(t => !t.Columns.Any(c => c.IsPrimaryKey)))
        {
            sb.AppendLine();
            sb.AppendLine("    protected override void OnModelCreating(ModelBuilder modelBuilder)");
            sb.AppendLine("    {");
            foreach (LinqTableSchema table in schema.Tables.Where(t => !t.Columns.Any(c => c.IsPrimaryKey)))
            {
                sb.AppendLine($"        modelBuilder.Entity<{table.EntityTypeName}>().HasNoKey();");
            }
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string GenerateCsvContext(LinqDatabaseSchema schema, string? targetPathLiteral)
    {
        StringBuilder sb = new();
        AppendTabularHeader(sb, schema);
        sb.AppendLine($"public sealed class {DefaultContextTypeName} : IDisposable");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly string _path;");
        sb.AppendLine();
        sb.AppendLine($"    public {DefaultContextTypeName}(string? path = null)");
        sb.AppendLine("    {");
        string fallback = targetPathLiteral is null ? "string.Empty" : Quote(targetPathLiteral);
        sb.AppendLine($"        _path = path ?? Environment.GetEnvironmentVariable(\"PASSENGER_LINQ_CONNECTION\") ?? {fallback};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Dispose() { }");
        sb.AppendLine();

        if (schema.Tables.Count > 0)
        {
            LinqTableSchema table = schema.Tables[0];
            sb.AppendLine($"    private IReadOnlyList<{table.EntityTypeName}>? _cached;");
            sb.AppendLine($"    public IReadOnlyList<{table.EntityTypeName}> {table.PropertyName} => _cached ??= Load();");
            sb.AppendLine();
            sb.AppendLine($"    private List<{table.EntityTypeName}> Load()");
            sb.AppendLine("    {");
            sb.AppendLine("        var rows = new List<" + table.EntityTypeName + ">();");
            sb.AppendLine("        if (!File.Exists(_path)) { return rows; }");
            sb.AppendLine("        using var reader = new StreamReader(new FileStream(_path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite), Encoding.UTF8, detectEncodingFromByteOrderMarks: true);");
            sb.AppendLine("        string? header = reader.ReadLine();");
            sb.AppendLine("        if (header is null) { return rows; }");
            sb.AppendLine("        while (reader.ReadLine() is { } line)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (string.IsNullOrWhiteSpace(line)) { continue; }");
            sb.AppendLine("            string[] f = ParseCsv(line);");
            sb.AppendLine($"            rows.Add(new {table.EntityTypeName}");
            sb.AppendLine("            {");
            for (int i = 0; i < table.Columns.Count; i++)
            {
                LinqColumnSchema col = table.Columns[i];
                sb.AppendLine($"                {col.PropertyName} = {EmitParseExpression($"({i} < f.Length ? f[{i}] : string.Empty)", col)},");
            }
            sb.AppendLine("            });");
            sb.AppendLine("        }");
            sb.AppendLine("        return rows;");
            sb.AppendLine("    }");
            AppendCsvParserHelper(sb);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string GenerateXlsxContext(LinqDatabaseSchema schema, string? targetPathLiteral)
    {
        StringBuilder sb = new();
        AppendTabularHeader(sb, schema, includeZipAndXml: true);
        sb.AppendLine($"public sealed class {DefaultContextTypeName} : IDisposable");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly string _path;");
        sb.AppendLine("    private Dictionary<string, List<string[]>>? _sheets;");
        sb.AppendLine();
        sb.AppendLine($"    public {DefaultContextTypeName}(string? path = null)");
        sb.AppendLine("    {");
        string fallback = targetPathLiteral is null ? "string.Empty" : Quote(targetPathLiteral);
        sb.AppendLine($"        _path = path ?? Environment.GetEnvironmentVariable(\"PASSENGER_LINQ_CONNECTION\") ?? {fallback};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Dispose() { }");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            string fieldName = "_sheet_" + table.PropertyName.TrimStart('@');
            sb.AppendLine($"    private IReadOnlyList<{table.EntityTypeName}>? {fieldName};");
            sb.AppendLine($"    public IReadOnlyList<{table.EntityTypeName}> {table.PropertyName} => {fieldName} ??= LoadSheet({Quote(table.TableName)}, f => new {table.EntityTypeName}");
            sb.AppendLine("    {");
            for (int i = 0; i < table.Columns.Count; i++)
            {
                LinqColumnSchema col = table.Columns[i];
                sb.AppendLine($"        {col.PropertyName} = {EmitParseExpression($"({i} < f.Length ? f[{i}] : string.Empty)", col)},");
            }
            sb.AppendLine("    });");
            sb.AppendLine();
        }

        AppendXlsxReaderHelper(sb);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendTabularHeader(StringBuilder sb, LinqDatabaseSchema schema, bool includeZipAndXml = false)
    {
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using System.IO;");
        if (includeZipAndXml)
        {
            sb.AppendLine("using System.IO.Compression;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using System.Xml.Linq;");
        }
        sb.AppendLine("using System.Text;");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            sb.AppendLine($"public sealed class {table.EntityTypeName}");
            sb.AppendLine("{");
            foreach (LinqColumnSchema col in table.Columns)
            {
                string typeDecl = col.IsNullable && !col.ClrTypeName.EndsWith('?') ? col.ClrTypeName + "?" : col.ClrTypeName;
                string defaultInit = !col.IsNullable && col.ClrTypeName == "string" ? " = string.Empty;" : string.Empty;
                sb.AppendLine($"    public {typeDecl} {col.PropertyName} {{ get; set; }}{defaultInit}");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }
    }

    private static string EmitParseExpression(string rawExpr, LinqColumnSchema col) => (col.ClrTypeName, col.IsNullable) switch
    {
        ("long", false) => $"long.TryParse({rawExpr}, NumberStyles.Integer, CultureInfo.InvariantCulture, out var _v) ? _v : 0L",
        ("long", true) => $"long.TryParse({rawExpr}, NumberStyles.Integer, CultureInfo.InvariantCulture, out var _v) ? _v : (long?)null",
        ("decimal", false) => $"decimal.TryParse({rawExpr}, NumberStyles.Number, CultureInfo.InvariantCulture, out var _v) ? _v : 0m",
        ("decimal", true) => $"decimal.TryParse({rawExpr}, NumberStyles.Number, CultureInfo.InvariantCulture, out var _v) ? _v : (decimal?)null",
        ("bool", false) => $"bool.TryParse({rawExpr}, out var _v) && _v",
        ("bool", true) => $"bool.TryParse({rawExpr}, out var _v) ? _v : (bool?)null",
        ("DateTime", false) => $"DateTime.TryParse({rawExpr}, CultureInfo.InvariantCulture, DateTimeStyles.None, out var _v) ? _v : default",
        ("DateTime", true) => $"DateTime.TryParse({rawExpr}, CultureInfo.InvariantCulture, DateTimeStyles.None, out var _v) ? _v : (DateTime?)null",
        (_, true) => $"string.IsNullOrEmpty({rawExpr}) ? null : {rawExpr}",
        _ => rawExpr,
    };

    private static void AppendCsvParserHelper(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("    private static string[] ParseCsv(string line)");
        sb.AppendLine("    {");
        sb.AppendLine("        var fields = new List<string>();");
        sb.AppendLine("        var cur = new StringBuilder();");
        sb.AppendLine("        bool inQuotes = false;");
        sb.AppendLine("        for (int i = 0; i < line.Length; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            char c = line[i];");
        sb.AppendLine("            if (inQuotes)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (c == '\"' && i + 1 < line.Length && line[i + 1] == '\"') { cur.Append('\"'); i++; }");
        sb.AppendLine("                else if (c == '\"') { inQuotes = false; }");
        sb.AppendLine("                else { cur.Append(c); }");
        sb.AppendLine("            }");
        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                if (c == '\"') { inQuotes = true; }");
        sb.AppendLine("                else if (c == ',') { fields.Add(cur.ToString()); cur.Clear(); }");
        sb.AppendLine("                else { cur.Append(c); }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        fields.Add(cur.ToString());");
        sb.AppendLine("        return fields.ToArray();");
        sb.AppendLine("    }");
    }

    private static void AppendXlsxReaderHelper(StringBuilder sb)
    {
        sb.AppendLine("    private List<T> LoadSheet<T>(string sheetName, Func<string[], T> map)");
        sb.AppendLine("    {");
        sb.AppendLine("        _sheets ??= ReadAllSheets();");
        sb.AppendLine("        var result = new List<T>();");
        sb.AppendLine("        if (!_sheets.TryGetValue(sheetName, out var rows) || rows.Count <= 1) { return result; }");
        sb.AppendLine("        for (int i = 1; i < rows.Count; i++) { result.Add(map(rows[i])); }");
        sb.AppendLine("        return result;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private Dictionary<string, List<string[]>> ReadAllSheets()");
        sb.AppendLine("    {");
        sb.AppendLine("        var map = new Dictionary<string, List<string[]>>(StringComparer.Ordinal);");
        sb.AppendLine("        if (!File.Exists(_path)) { return map; }");
        sb.AppendLine("        using var fs = new FileStream(_path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);");
        sb.AppendLine("        using var zip = new ZipArchive(fs, ZipArchiveMode.Read);");
        sb.AppendLine("        var sst = new List<string>();");
        sb.AppendLine("        var sstEntry = zip.GetEntry(\"xl/sharedStrings.xml\");");
        sb.AppendLine("        if (sstEntry is not null)");
        sb.AppendLine("        {");
        sb.AppendLine("            using var s = sstEntry.Open();");
        sb.AppendLine("            var doc = XDocument.Load(s);");
        sb.AppendLine("            var ns = doc.Root?.Name.Namespace ?? XNamespace.None;");
        sb.AppendLine("            foreach (var si in doc.Descendants(ns + \"si\")) { sst.Add(string.Concat(si.Descendants(ns + \"t\").Select(t => t.Value))); }");
        sb.AppendLine("        }");
        sb.AppendLine("        var wbEntry = zip.GetEntry(\"xl/workbook.xml\");");
        sb.AppendLine("        var relsEntry = zip.GetEntry(\"xl/_rels/workbook.xml.rels\");");
        sb.AppendLine("        if (wbEntry is null || relsEntry is null) { return map; }");
        sb.AppendLine("        var relTargets = new Dictionary<string, string>(StringComparer.Ordinal);");
        sb.AppendLine("        using (var rs = relsEntry.Open())");
        sb.AppendLine("        {");
        sb.AppendLine("            var relDoc = XDocument.Load(rs);");
        sb.AppendLine("            foreach (var rel in relDoc.Root?.Elements() ?? Array.Empty<XElement>())");
        sb.AppendLine("            {");
        sb.AppendLine("                var id = (string?)rel.Attribute(\"Id\"); var target = (string?)rel.Attribute(\"Target\");");
        sb.AppendLine("                if (id is not null && target is not null)");
        sb.AppendLine("                {");
        sb.AppendLine("                    var norm = target.TrimStart('/');");
        sb.AppendLine("                    if (!norm.StartsWith(\"xl/\", StringComparison.OrdinalIgnoreCase)) { norm = \"xl/\" + norm; }");
        sb.AppendLine("                    relTargets[id] = norm;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        using var ws = wbEntry.Open();");
        sb.AppendLine("        var wbDoc = XDocument.Load(ws);");
        sb.AppendLine("        var mainNs = wbDoc.Root?.Name.Namespace ?? XNamespace.None;");
        sb.AppendLine("        XNamespace relNs = \"http://schemas.openxmlformats.org/officeDocument/2006/relationships\";");
        sb.AppendLine("        foreach (var sheet in wbDoc.Descendants(mainNs + \"sheet\"))");
        sb.AppendLine("        {");
        sb.AppendLine("            var name = (string?)sheet.Attribute(\"name\") ?? \"Sheet\";");
        sb.AppendLine("            var rId = (string?)sheet.Attribute(relNs + \"id\");");
        sb.AppendLine("            if (rId is null || !relTargets.TryGetValue(rId, out var entryPath)) { continue; }");
        sb.AppendLine("            var sheetEntry = zip.GetEntry(entryPath);");
        sb.AppendLine("            if (sheetEntry is null) { continue; }");
        sb.AppendLine("            using var ss = sheetEntry.Open();");
        sb.AppendLine("            var sDoc = XDocument.Load(ss);");
        sb.AppendLine("            var ns = sDoc.Root?.Name.Namespace ?? XNamespace.None;");
        sb.AppendLine("            var rows = new List<string[]>();");
        sb.AppendLine("            foreach (var rowEl in sDoc.Descendants(ns + \"row\"))");
        sb.AppendLine("            {");
        sb.AppendLine("                var row = new List<string>();");
        sb.AppendLine("                foreach (var cEl in rowEl.Elements(ns + \"c\"))");
        sb.AppendLine("                {");
        sb.AppendLine("                    int colIdx = ColIdx((string?)cEl.Attribute(\"r\"), row.Count);");
        sb.AppendLine("                    while (row.Count < colIdx) { row.Add(string.Empty); }");
        sb.AppendLine("                    var ct = (string?)cEl.Attribute(\"t\");");
        sb.AppendLine("                    var rv = (string?)cEl.Element(ns + \"v\") ?? string.Empty;");
        sb.AppendLine("                    var v = ct == \"s\" && int.TryParse(rv, NumberStyles.Integer, CultureInfo.InvariantCulture, out var idx) && idx >= 0 && idx < sst.Count ? sst[idx]");
        sb.AppendLine("                        : ct == \"inlineStr\" ? string.Concat(cEl.Descendants(ns + \"t\").Select(t => t.Value))");
        sb.AppendLine("                        : ct == \"b\" ? (rv == \"1\" ? \"true\" : \"false\") : rv;");
        sb.AppendLine("                    row.Add(v);");
        sb.AppendLine("                }");
        sb.AppendLine("                rows.Add(row.ToArray());");
        sb.AppendLine("            }");
        sb.AppendLine("            map[name] = rows;");
        sb.AppendLine("        }");
        sb.AppendLine("        return map;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static int ColIdx(string? r, int fallback)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (string.IsNullOrEmpty(r)) { return fallback; }");
        sb.AppendLine("        int col = 0;");
        sb.AppendLine("        foreach (char ch in r)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (ch is >= 'A' and <= 'Z') { col = col * 26 + (ch - 'A' + 1); }");
        sb.AppendLine("            else if (ch is >= 'a' and <= 'z') { col = col * 26 + (ch - 'a' + 1); }");
        sb.AppendLine("            else { break; }");
        sb.AppendLine("        }");
        sb.AppendLine("        return col > 0 ? col - 1 : fallback;");
        sb.AppendLine("    }");
    }

    private static string GenerateMySqlContext(LinqDatabaseSchema schema)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using MySqlConnector;");
        sb.AppendLine("using Passenger.Linq.Runtime;");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            sb.AppendLine($"public sealed class {table.EntityTypeName}");
            sb.AppendLine("{");
            foreach (LinqColumnSchema col in table.Columns)
            {
                string typeDecl = col.IsNullable && !col.ClrTypeName.EndsWith('?') ? col.ClrTypeName + "?" : col.ClrTypeName;
                string defaultInit = !col.IsNullable && col.ClrTypeName is "string" or "byte[]" ? " = default!;" : string.Empty;
                sb.AppendLine($"    public {typeDecl} {col.PropertyName} {{ get; set; }}{defaultInit}");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine($"public sealed class {DefaultContextTypeName} : IDisposable");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly string _connectionString;");
        sb.AppendLine();
        sb.AppendLine($"    public {DefaultContextTypeName}(string? connectionString = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        _connectionString = !string.IsNullOrEmpty(connectionString)");
        sb.AppendLine("            ? connectionString");
        sb.AppendLine("            : Environment.GetEnvironmentVariable(\"PASSENGER_LINQ_CONNECTION\") ?? string.Empty;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Dispose() { }");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            sb.AppendLine($"    private IReadOnlyList<{table.EntityTypeName}>? _{table.PropertyName};");
            sb.AppendLine($"    public IReadOnlyList<{table.EntityTypeName}> {table.PropertyName} => _{table.PropertyName} ??= Load_{table.PropertyName}();");
            sb.AppendLine();
            sb.AppendLine($"    private List<{table.EntityTypeName}> Load_{table.PropertyName}()");
            sb.AppendLine("    {");
            sb.AppendLine($"        var rows = new List<{table.EntityTypeName}>();");
            sb.AppendLine("        using var conn = new MySqlConnection(_connectionString);");
            sb.AppendLine("        conn.Open();");
            string colsSelect = string.Join(", ", table.Columns.Select(c => $"`{c.Name.Replace("`", "``", StringComparison.Ordinal)}`"));
            string sqlLit = $"SELECT {colsSelect} FROM `{table.TableName.Replace("`", "``", StringComparison.Ordinal)}`";
            sb.AppendLine($"        string sql = {Quote(sqlLit)};");
            sb.AppendLine("        LinqExtensions.LogSql(sql);");
            sb.AppendLine("        using var cmd = new MySqlCommand(sql, conn);");
            sb.AppendLine("        using var reader = cmd.ExecuteReader();");
            sb.AppendLine("        while (reader.Read())");
            sb.AppendLine("        {");
            sb.AppendLine($"            rows.Add(new {table.EntityTypeName}");
            sb.AppendLine("            {");
            for (int i = 0; i < table.Columns.Count; i++)
            {
                LinqColumnSchema col = table.Columns[i];
                sb.AppendLine($"                {col.PropertyName} = {EmitMySqlReadExpression(i, col)},");
            }
            sb.AppendLine("            });");
            sb.AppendLine("        }");
            sb.AppendLine("        return rows;");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitMySqlReadExpression(int index, LinqColumnSchema col)
    {
        string raw = $"reader.GetValue({index})";
        string baseType = col.ClrTypeName.TrimEnd('?');
        string conv = baseType switch
        {
            "sbyte" => $"Convert.ToSByte({raw}, CultureInfo.InvariantCulture)",
            "short" => $"Convert.ToInt16({raw}, CultureInfo.InvariantCulture)",
            "int" => $"Convert.ToInt32({raw}, CultureInfo.InvariantCulture)",
            "long" => $"Convert.ToInt64({raw}, CultureInfo.InvariantCulture)",
            "float" => $"Convert.ToSingle({raw}, CultureInfo.InvariantCulture)",
            "double" => $"Convert.ToDouble({raw}, CultureInfo.InvariantCulture)",
            "decimal" => $"Convert.ToDecimal({raw}, CultureInfo.InvariantCulture)",
            "bool" => $"Convert.ToBoolean({raw}, CultureInfo.InvariantCulture)",
            "DateTime" => $"Convert.ToDateTime({raw}, CultureInfo.InvariantCulture)",
            "TimeSpan" => $"({raw} is TimeSpan ts ? ts : TimeSpan.Parse(Convert.ToString({raw}, CultureInfo.InvariantCulture) ?? \"0\", CultureInfo.InvariantCulture))",
            "byte[]" => $"(byte[]){raw}",
            _ => $"Convert.ToString({raw}, CultureInfo.InvariantCulture) ?? string.Empty",
        };
        if (col.IsNullable)
        {
            return $"reader.IsDBNull({index}) ? null : {conv}";
        }
        return $"reader.IsDBNull({index}) ? default! : {conv}";
    }

    private static string GenerateJsonContext(LinqDatabaseSchema schema, string? targetPathLiteral)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine();

        foreach (LinqTableSchema table in schema.Tables)
        {
            sb.AppendLine($"public sealed class {table.EntityTypeName}");
            sb.AppendLine("{");
            foreach (LinqColumnSchema col in table.Columns)
            {
                string typeDecl = col.IsNullable && !col.ClrTypeName.EndsWith('?') ? col.ClrTypeName + "?" : col.ClrTypeName;
                string defaultInit = !col.IsNullable && col.ClrTypeName is "string" or "byte[]" ? " = default!;" : string.Empty;
                sb.AppendLine($"    public {typeDecl} {col.PropertyName} {{ get; set; }}{defaultInit}");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine($"public sealed class {DefaultContextTypeName} : IDisposable");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly string _path;");
        sb.AppendLine();
        sb.AppendLine($"    public {DefaultContextTypeName}(string? path = null)");
        sb.AppendLine("    {");
        string fallback = targetPathLiteral is null ? "string.Empty" : Quote(targetPathLiteral);
        sb.AppendLine($"        _path = path ?? Environment.GetEnvironmentVariable(\"PASSENGER_LINQ_CONNECTION\") ?? {fallback};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Dispose() { }");
        sb.AppendLine();

        for (int t = 0; t < schema.Tables.Count; t++)
        {
            LinqTableSchema table = schema.Tables[t];
            sb.AppendLine($"    private IReadOnlyList<{table.EntityTypeName}>? _cached{t};");
            sb.AppendLine($"    public IReadOnlyList<{table.EntityTypeName}> {table.PropertyName} => _cached{t} ??= LoadTable{t}();");
            sb.AppendLine();
            sb.AppendLine($"    private List<{table.EntityTypeName}> LoadTable{t}()");
            sb.AppendLine("    {");
            sb.AppendLine($"        var rows = new List<{table.EntityTypeName}>();");
            sb.AppendLine("        if (!File.Exists(_path)) { return rows; }");
            sb.AppendLine("        using var fs = new FileStream(_path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);");
            sb.AppendLine("        using var doc = JsonDocument.Parse(fs);");
            sb.AppendLine("        JsonElement arr = default;");
            sb.AppendLine("        if (doc.RootElement.ValueKind == JsonValueKind.Array)");
            sb.AppendLine("        {");
            sb.AppendLine("            arr = doc.RootElement;");
            sb.AppendLine("        }");
            sb.AppendLine($"        else if (doc.RootElement.ValueKind == JsonValueKind.Object && doc.RootElement.TryGetProperty({Quote(table.TableName)}, out var prop) && prop.ValueKind == JsonValueKind.Array)");
            sb.AppendLine("        {");
            sb.AppendLine("            arr = prop;");
            sb.AppendLine("        }");
            sb.AppendLine("        if (arr.ValueKind == JsonValueKind.Array)");
            sb.AppendLine("        {");
            sb.AppendLine("            foreach (var item in arr.EnumerateArray())");
            sb.AppendLine("            {");
            sb.AppendLine("                if (item.ValueKind != JsonValueKind.Object) { continue; }");
            sb.AppendLine($"                rows.Add(Map{t}(item));");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("        else if (doc.RootElement.ValueKind == JsonValueKind.Object)");
            sb.AppendLine("        {");
            sb.AppendLine($"            rows.Add(Map{t}(doc.RootElement));");
            sb.AppendLine("        }");
            sb.AppendLine("        return rows;");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    private static {table.EntityTypeName} Map{t}(JsonElement el)");
            sb.AppendLine("    {");
            sb.AppendLine($"        return new {table.EntityTypeName}");
            sb.AppendLine("        {");
            foreach (LinqColumnSchema col in table.Columns)
            {
                sb.AppendLine($"            {col.PropertyName} = {EmitJsonReadExpression(col)},");
            }
            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitJsonReadExpression(LinqColumnSchema col)
    {
        string propLit = Quote(col.Name);
        string baseType = col.ClrTypeName.TrimEnd('?');
        string conv = baseType switch
        {
            "long" => $"(el.TryGetProperty({propLit}, out var p) && p.ValueKind == JsonValueKind.Number && p.TryGetInt64(out var v) ? v : {(col.IsNullable ? "(long?)null" : "0L")})",
            "decimal" => $"(el.TryGetProperty({propLit}, out var p) && p.ValueKind == JsonValueKind.Number && p.TryGetDecimal(out var v) ? v : {(col.IsNullable ? "(decimal?)null" : "0m")})",
            "bool" => $"(el.TryGetProperty({propLit}, out var p) && (p.ValueKind == JsonValueKind.True || p.ValueKind == JsonValueKind.False) ? p.GetBoolean() : {(col.IsNullable ? "(bool?)null" : "false")})",
            _ => $"(el.TryGetProperty({propLit}, out var p) && p.ValueKind != JsonValueKind.Null && p.ValueKind != JsonValueKind.Undefined ? (p.ValueKind == JsonValueKind.String ? p.GetString() : p.GetRawText()) : {(col.IsNullable ? "null" : "string.Empty")})",
        };
        return conv;
    }

    private static string Quote(string s) => "\"" + s.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}
